-- H2(MySQL 兼容模式) 测试库：只建签发作业链路触及的六张表，列与实体逐列对齐
CREATE TABLE IF NOT EXISTS t_heri_job (
  id BIGINT NOT NULL,
  job_no VARCHAR(32),
  job_name VARCHAR(64),
  status INT,
  total_rows INT,
  done_rows INT,
  fail_rows INT,
  eff_start DATETIME,
  eff_end DATETIME,
  version VARCHAR(32),
  row_no INT,
  bl_no VARCHAR(64),
  amount DECIMAL(14,2),
  job_qty INT,
  version_status INT,
  writeback_flag INT,
  compensate_flag INT,
  compensated INT,
  compensate_cnt INT,
  fail_reason VARCHAR(255),
  del_flag INT DEFAULT 0,
  create_by VARCHAR(64),
  create_time DATETIME,
  update_by VARCHAR(64),
  update_time DATETIME,
  remark VARCHAR(500),
  PRIMARY KEY (id),
  CONSTRAINT uk_job_head UNIQUE (job_no, row_no)
);

